# frozen_string_literal: true

require 'yaml'

module Railglue
  # Builds the docker compose file for a Config.
  module Compose
    HEADER = "# Generated by bin/railglue from railglue.yml. Do not edit.\n"
    IMAGE_CONTEXT = File.join(ROOT, 'docker', 'app')

    module_function

    def render(config)
      HEADER + YAML.dump(build(config))
    end

    def build(config)
      {
        'name' => config.project,
        'services' => services(config),
        'volumes' => volumes(config)
      }
    end

    def services(config)
      result = { 'nginx' => nginx_service(config) }
      config.apps.each { |app| result[app.name] = app_service(config, app) }
      database_services(config).each do |name|
        result[name] = Databases.compose_service(name, config.image(name))
      end
      result
    end

    def database_services(config)
      config.apps.filter_map { |app| Databases.service_for(app) }.uniq
    end

    def volumes(config)
      names = ['mise'] + config.apps.map { |app| bundle_volume(app) } +
              database_services(config)
      names.to_h { |name| [name, {}] }
    end

    def bundle_volume(app)
      "bundle-#{app.name}"
    end

    def nginx_service(config)
      {
        'image' => config.image('nginx'),
        'ports' => ["127.0.0.1:#{config.port}:80"],
        'volumes' =>
          ["#{config.nginx_path}:/etc/nginx/conf.d/default.conf:ro"],
        'depends_on' => config.apps.map(&:name)
      }
    end

    def app_service(config, app)
      service = {
        'image' => "#{config.project}-app",
        'build' => build_spec,
        'environment' => app_environment(app),
        'volumes' => app_volumes(app),
        'shm_size' => '1gb',
        'stdin_open' => true,
        'tty' => true
      }
      database = Databases.service_for(app)
      service['depends_on'] = healthy(database) if database
      service
    end

    def healthy(service)
      { service => { 'condition' => 'service_healthy' } }
    end

    def build_spec
      {
        'context' => IMAGE_CONTEXT,
        'args' => { 'UID' => Process.uid.to_s, 'GID' => Process.gid.to_s }
      }
    end

    def app_volumes(app)
      ["#{app.path}:/app", 'mise:/mise', "#{bundle_volume(app)}:/bundle"]
    end

    def app_environment(app)
      env = {
        'PORT' => APP_PORT.to_s,
        'RAILGLUE_APP' => app.name,
        'RAILGLUE_MOUNT_PATH' => app.mount
      }
      env['RAILS_RELATIVE_URL_ROOT'] = app.mount unless app.root?
      database_environment(app).merge(env)
    end

    def database_environment(app)
      return {} unless Databases.service_for(app)

      {
        'DATABASE_URL' => Databases.url(app, 'development'),
        'RAILGLUE_TEST_DATABASE_URL' => Databases.url(app, 'test')
      }
    end
  end
end
